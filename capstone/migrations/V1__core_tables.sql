CREATE TABLE tenants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
 email VARCHAR(254) NOT NULL,
 display_name VARCHAR(120) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT uq_app_users_tenant_id_id UNIQUE (tenant_id, id),
 CONSTRAINT uq_app_users_tenant_email UNIQUE (tenant_id, email),
 CONSTRAINT ck_app_users_email CHECK (position('@' IN email) > 1)
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
 name VARCHAR(80) NOT NULL CHECK (length(trim(name)) > 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT uq_categories_tenant_id_id UNIQUE (tenant_id, id),
 CONSTRAINT uq_categories_tenant_name UNIQUE (tenant_id, name)
);
CREATE TABLE expenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
 currency CHAR(3) NOT NULL DEFAULT 'KES' CHECK (currency ~ '^[A-Z]{3}$'),
 description VARCHAR(500),
 spent_on DATE NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT fk_expenses_category_tenant FOREIGN KEY (tenant_id, category_id)
   REFERENCES categories (tenant_id, id),
 CONSTRAINT fk_expenses_creator_tenant FOREIGN KEY (tenant_id, created_by)
   REFERENCES app_users (tenant_id, id)
);
