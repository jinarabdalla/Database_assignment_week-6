CREATE TABLE expense_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT,
 expense_id BIGINT,
 action VARCHAR(10) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 changed_by TEXT,
 old_row JSONB,
 new_row JSONB
);
CREATE INDEX idx_expense_audit_tenant_changed_at ON expense_audit (tenant_id, changed_at DESC);

CREATE OR REPLACE FUNCTION audit_expense_change()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public AS $$
BEGIN
 IF TG_OP = 'INSERT' THEN
  INSERT INTO public.expense_audit(tenant_id, expense_id, action, changed_by, new_row)
  VALUES(NEW.tenant_id, NEW.id, TG_OP, current_setting('app.user_id', true), to_jsonb(NEW));
  RETURN NEW;
 ELSIF TG_OP = 'UPDATE' THEN
  NEW.updated_at := now();
  INSERT INTO public.expense_audit(tenant_id, expense_id, action, changed_by, old_row, new_row)
  VALUES(NEW.tenant_id, NEW.id, TG_OP, current_setting('app.user_id', true), to_jsonb(OLD), to_jsonb(NEW));
  RETURN NEW;
 ELSE
  INSERT INTO public.expense_audit(tenant_id, expense_id, action, changed_by, old_row)
  VALUES(OLD.tenant_id, OLD.id, TG_OP, current_setting('app.user_id', true), to_jsonb(OLD));
  RETURN OLD;
 END IF;
END;
$$;

-- BEFORE ensures updated_at and audit snapshots are captured before row storage.
CREATE TRIGGER trg_expenses_audit
BEFORE INSERT OR UPDATE OR DELETE ON expenses
FOR EACH ROW EXECUTE FUNCTION audit_expense_change();
